"""§7.3 Corrientes 2022 backtest + 2003–2021 honesty table, using the pre-registered rule (alerts.py)."""
from __future__ import annotations

import json
from datetime import date

import pandas as pd

from pipeline import config as C
from pipeline.alerts import evaluate, first_dates, signal, thresholds
from pipeline.harmonize import daily_components, harmonize


def province_daily_h() -> pd.DataFrame:
    cells = pd.read_parquet(C.PROCESSED / "cells.parquet")
    cov = pd.read_parquet(C.PROCESSED / "coverage.parquet")
    cd = pd.read_parquet(C.PROCESSED / "cell_day.parquet")
    cal = json.loads((C.PROCESSED / "calibration.json").read_text())
    ik = lambda d: {int(k): v for k, v in d.items()}  # noqa: E731
    region = set(cells.loc[cells.in_region, "cell_id"])
    daily = daily_components(cd[cd.cell_id.isin(region)], cov)
    return harmonize(daily, ik(cal["k_M"]), ik(cal["k_V"]), ik(cal["k_M_ci"]), ik(cal["k_V_ci"]))


def lead_lag(first: str | None, marker_date: str) -> int | None:
    if not first:
        return None
    return (date.fromisoformat(marker_date) - date.fromisoformat(first)).days


def run(dh: pd.DataFrame) -> dict:
    sig = signal(dh)
    thr = thresholds(sig)
    ev = evaluate(sig, thr)
    s0, s1 = C.BACKTEST_SEASON
    target = first_dates(ev, s0, s1)
    markers = []
    for m in C.OFFICIAL_MARKERS:
        markers.append({**m,
                        "days_after_first_alert": lead_lag(target["first_alert"], m["date"]),
                        "days_after_first_severe": lead_lag(target["first_severe"], m["date"])})
    honesty = []
    for y in range(C.ALERT_RULE["baseline_years"][0], C.ALERT_RULE["baseline_years"][1] + 1):
        r = first_dates(ev, f"{y - 1}-11-01", f"{y}-03-31")
        yr = ev[ev.year == y]
        honesty.append({"season": f"{y - 1}-11 → {y}-03", "alert": r["first_alert"] is not None,
                        "severe": r["first_severe"] is not None, **r,
                        "calendar_year_alert_days": int(yr.alert.sum()),
                        "calendar_year_severe_days": int(yr.severe.sum())})
    n = len(honesty)
    na = sum(h["alert"] for h in honesty)
    ns = sum(h["severe"] for h in honesty)
    win = ev[(ev.solar_date >= date.fromisoformat("2021-11-01")) & (ev.solar_date <= date.fromisoformat("2022-03-31"))]
    return {
        "rule": C.ALERT_RULE,
        "aoi": "Corrientes province (geoBoundaries ADM1)",
        "season": {"start": s0, "end": s1},
        "result": target,
        "markers": markers,
        "honesty": {"seasons": honesty, "n_seasons": n, "n_alert": na, "n_severe": ns,
                    "sentence": f"This rule fired in {na} of {n} seasons (Nov–Mar, 2003–2021); Severe in {ns}.",
                    "note": "The 2003–2021 seasons are part of the baseline, so this is an in-sample false-alarm rate."},
        "timeline": [{"date": str(r.solar_date), "H": None if pd.isna(r.H) else round(float(r.H), 2),
                      "S": None if pd.isna(r.S) else round(float(r.S), 2),
                      "P90": None if pd.isna(r.P90) else round(float(r.P90), 2),
                      "P99": None if pd.isna(r.P99) else round(float(r.P99), 2),
                      "alert": bool(r.alert), "severe": bool(r.severe), "status": r.status}
                     for r in win.itertuples()],
        "reported_official": [{"fact": "INTA Corrientes report (18 Feb 2022): burned area growing ~30,000 ha per day "
                                       "in recent days (cited inside DNU 335/2022)",
                               "label": "reported (official source)", "verified": False,
                               "source_url": C.OFFICIAL_MARKERS[3]["source_url"]}],
    }


def methods_block(bt: dict) -> str:
    r = bt["result"]
    L = ["### Backtest results (auto-generated by `pipeline/backtest.py`, run after the rule was recorded)", "",
         f"Season {bt['season']['start']} → {bt['season']['end']}, {bt['aoi']}.", "",
         f"- First Alert (S > P90, 3 days): **{r['first_alert'] or 'none'}**",
         f"- First Severe (S > P99, 3 days): **{r['first_severe'] or 'none'}**",
         f"- Alert days in season: {r['alert_days']}, Severe days: {r['severe_days']}, no-data days: {r['no_data_days']}",
         "", "| Official marker | Date | Verified | Days after first Alert | Days after first Severe |",
         "|---|---|---|---|---|"]
    for m in bt["markers"]:
        L.append(f"| {m['label']} | {m['date']} | {'yes' if m['verified'] else 'no'} | "
                 f"{m['days_after_first_alert']} | {m['days_after_first_severe']} |")
    h = bt["honesty"]
    L += ["", f"**Honesty check:** {h['sentence']} {h['note']}", "",
          "| Season | Alert | First alert | Severe | First severe |", "|---|---|---|---|---|"]
    for s in h["seasons"]:
        L.append(f"| {s['season']} | {'yes' if s['alert'] else 'no'} | {s['first_alert'] or '—'} | "
                 f"{'yes' if s['severe'] else 'no'} | {s['first_severe'] or '—'} |")
    L += ["", "Positive numbers mean the decree came after our first alert. No causal claim is made."]
    return "\n".join(L)


def main() -> dict:
    bt = run(province_daily_h())
    (C.PROCESSED / "backtest_corrientes_2022.json").write_text(json.dumps(bt, indent=2, ensure_ascii=False))
    from pipeline.methods_doc import update_block

    update_block("BACKTEST", methods_block(bt))
    print(json.dumps(bt["result"], indent=1))
    for m in bt["markers"]:
        print(f"  {m['date']} {m['label'][:60]:60s} +{m['days_after_first_alert']}d after alert")
    print(bt["honesty"]["sentence"])
    return bt


if __name__ == "__main__":
    main()
